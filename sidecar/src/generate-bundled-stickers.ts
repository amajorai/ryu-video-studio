/**
 * Regenerates `bundled-stickers.ts` from the sticker catalog: one literal
 * text import per bundled SVG, so `bun build --compile` embeds every sticker
 * in the sidecar binary. Run after changing `shared/stickers/assets`:
 *
 *   bun sidecar/src/generate-bundled-stickers.ts
 *   bun x ultracite fix sidecar/src/bundled-stickers.ts
 */
import { writeFile } from "node:fs/promises";
import { join } from "node:path";
import { STICKER_CATALOG } from "../../shared/stickers/catalog.ts";

/** A valid identifier for a sticker path such as `flags/us.svg`. */
export function stickerBinding(file: string): string {
	const words = file
		.replace(/\.svg$/, "")
		.split(/[^a-z0-9]+/)
		.filter(Boolean);
	return `sticker${words.map((word) => `${word[0]?.toUpperCase() ?? ""}${word.slice(1)}`).join("")}`;
}

export function bundledStickersSource(
	files: readonly string[] = STICKER_CATALOG.map((entry) => entry.file)
): string {
	const sorted = [...new Set(files)].sort();
	const imports = sorted.map(
		(file) =>
			`import ${stickerBinding(file)} from "../../shared/stickers/assets/${file}" with {\n\ttype: "text",\n};`
	);
	const rows = sorted.map((file) => `\t"${file}": ${stickerBinding(file)},`);
	return `/**
 * The bundled sticker artwork, embedded in the compiled sidecar as text so
 * \`GET /stickers\` and \`POST /projects/:id/stickers\` work from the bare
 * binary Core installs. Generated by \`generate-bundled-stickers.ts\`; do not
 * edit by hand. \`bundled-stickers.test.ts\` checks it matches the catalog.
 */
${imports.join("\n")}

/** SVG source of each bundled sticker, keyed by its catalog \`file\`. */
export const EMBEDDED_STICKERS: Readonly<Record<string, string>> = {
${rows.join("\n")}
};
`;
}

if (import.meta.main) {
	await writeFile(
		join(import.meta.dir, "bundled-stickers.ts"),
		bundledStickersSource()
	);
}
