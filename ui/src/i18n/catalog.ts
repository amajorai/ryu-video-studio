/**
 * ICU templates for copy built at runtime from values ("Marked {range}",
 * "Imported {count, plural, …}", sidecar errors that name a clip), formatted
 * by `studioFormat` in `format.ts` in the active host language. Kept apart
 * from `STUDIO_MESSAGES`, whose keys are literal DOM text.
 */
export const STUDIO_RUNTIME_MESSAGES: StudioMessages = STUDIO_RUNTIME_TEMPLATES;

/**
 * The catalogs as `RyuAppShell` message overlays: locale → English → text.
 * Besides the host's 11 official languages, the machine-drafted extra
 * catalogs (`extra/<locale>.json`) are layered for their locales; they take
 * effect once a host language pack for that locale is installed and
 * selected, and strings they lack stay English.
 */
export function studioMessageOverlays(): Record<
	string,
	Record<string, string>
> {
	const overlays: Record<string, Record<string, string>> = Object.fromEntries(
		STUDIO_LOCALES.map((locale) => [locale, {} as Record<string, string>])
	);
	for (const [source, translations] of Object.entries(STUDIO_MESSAGES)) {
		for (const locale of STUDIO_LOCALES) {
			const target = overlays[locale];
			if (target) {
				target[source] = translations[locale];
			}
		}
	}
	for (const [locale, messages] of Object.entries(EXTRA_LOCALE_CATALOGS)) {
		const literals: Record<string, string> = {};
		for (const [source, text] of Object.entries(messages)) {
			// Runtime templates are formatted by `studioFormat`, not swapped in
			// the DOM; only literal copy belongs in the overlay.
			if (Object.hasOwn(STUDIO_MESSAGES, source)) {
				literals[source] = text;
			}
		}
		overlays[locale] = literals;
	}
	return overlays;
}
